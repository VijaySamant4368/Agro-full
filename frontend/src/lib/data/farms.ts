export const getFarm = (slug: string) => FARMS.find((f) => f.slug === slug);

export interface FarmQuery {
  state?: string;
  district?: string;
  subDistrict?: string;
}

export function searchFarms({ state, district, subDistrict }: FarmQuery) {
  return FARMS.filter(
    (f) =>
      (!state || f.state.toLowerCase() === state.toLowerCase()) &&
      (!district || f.district.toLowerCase() === district.toLowerCase()) &&
      (!subDistrict || f.subDistrict?.toLowerCase() === subDistrict.toLowerCase()),
  );
}

